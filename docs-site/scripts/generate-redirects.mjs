// Generates redirect pages at the legacy Sphinx URLs so links to the previous
// documentation keep working after the switch to the Starlight site.
//
// Reads dist/api/pysm3/symbols.json (written by starlight-pydocs) to map each
// legacy per-symbol API page (e.g. api/pysm3.Sky.html) to its module page and
// anchor. Notebook and prose pages use fixed rules. Run after `astro build`.
//
// Usage: node scripts/generate-redirects.mjs   (run from docs-site/)

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { resolve, dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(scriptDir, '../dist');

const LEGACY_TUTORIALS = [
  'bandpass_integration', 'bandpass_sampling', 'bandpass_sampling_comparison',
  'basic_use', 'customize_components', 'model_data', 'mpi', 'smoothing_coord_rotation',
];
const LEGACY_PROSE = ['models', 'websky', 'contributing', 'pre_applied_beam', 'pysm_methods_author_contributions', 'co_lines'];
// API pages generated by automodapi on the old site (one page per top-level symbol).
const LEGACY_API = [
  'CMBDipole', 'CMBLensed', 'CMBMap', 'COLines', 'CurvedPowerLaw',
  'DecorrelatedModifiedBlackBody', 'HensleyDraine2017', 'InterpolatingComponent',
  'MapDistribution', 'Model', 'ModifiedBlackBody', 'ModifiedBlackBodyLayers',
  'ModifiedBlackBodyRealization', 'PointSourceCatalog', 'PowerLaw',
  'PowerLawRealization', 'SPT_CIB_map_scaling', 'SimpleSZ', 'Sky', 'SpDust',
  'SpDustPol', 'WebSkyCIB', 'WebSkyCMB', 'WebSkyRadioGalaxies',
  'apply_smoothing_and_coord_transform', 'bandpass_distribution_function',
  'bandpass_kresampling', 'bandpass_unit_conversion', 'check_freq_input',
  'compute_moments', 'get_differential_fwhm', 'get_pysm_emission', 'map2alm',
  'mpi_smoothing', 'normalize_weights', 'parse_pre_applied_fwhm', 'read_map',
  'resample_bandpass', 'search_optimal_kernel_bandwidth', 'set_verbosity',
];

function listNotebookDirs(base) {
  const out = [];
  for (const entry of readdirSync(base, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = join(base, entry.name);
    if (entry.isDirectory() && entry.name !== 'assets') {
      out.push(entry.name, ...listNotebookDirs(full).map((p) => `${entry.name}/${p}`));
    }
  }
  return out;
}

function redirectHtml(target) {
  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8" />',
    '<meta http-equiv="refresh" content="0; url=' + target + '" />',
    '<title>Redirecting...</title>',
    '</head>',
    '<body>',
    `<p>This page has moved to <a href="${target}">${target}</a>.</p>`,
    '</body>',
    '</html>',
    '',
  ].join('\n');
}

// Legacy slugs had mixed case for a few preprocessing notebooks (the new
// routes are lowercase, case-sensitive).
const LEGACY_CASE_SLUGS = {
  'preprocess-templates/gnilc_dust_spectralindex_Tdust.html': 'notebooks/preprocess-templates/gnilc_dust_spectralindex_tdust/',
  'preprocess-templates/utils_gnilc_generate_map_spectralindex_Td.html': 'notebooks/preprocess-templates/utils_gnilc_generate_map_spectralindex_td/',
};

const targets = []; // [legacyPathWithoutHtml, newPath]
for (const [oldPath, newPath] of Object.entries(LEGACY_CASE_SLUGS)) targets.push([oldPath, newPath]);

for (const name of LEGACY_PROSE) targets.push([`${name}.html`, `${name}/`]);
for (const name of LEGACY_TUTORIALS) targets.push([`${name}.html`, `notebooks/${name}/`]);
for (const rel of listNotebookDirs(join(distDir, 'notebooks', 'preprocess-templates'))) {
  targets.push([`preprocess-templates/${rel}.html`, `notebooks/preprocess-templates/${rel}/`]);
}
if (targets.length < 30) throw new Error('unexpected notebook dir listing: ' + targets.length);

let symbols = [];
try {
  symbols = JSON.parse(readFileSync(join(distDir, 'api/pysm3/symbols.json'), 'utf8')).symbols;
} catch {
  // no API build available; API redirects are skipped
}
const byName = new Map();
for (const s of symbols) {
  const short = s.path.split('.').slice(-1)[0];
  if (s.kind === 'class' || s.kind === 'function') {
    if (!byName.has(short)) byName.set(short, s);
  }
}
let api = 0;
for (const name of LEGACY_API) {
  const s = byName.get(name);
  if (!s || !s.page) continue;
  targets.push([`api/pysm3.${name}.html`, `${s.page}/#${s.anchor}`]);
  api += 1;
}
if (api < 35) throw new Error(`only ${api}/40 legacy API pages mapped`);

for (const [oldPath, newPath] of targets) {
  const out = join(distDir, oldPath);
  mkdirSync(dirname(out), { recursive: true });
  const prefix = '../'.repeat(oldPath.split('/').length - 1);
  writeFileSync(out, redirectHtml(prefix + newPath));
}
console.log(`Wrote ${targets.length} legacy redirect pages (${api} API).`);
